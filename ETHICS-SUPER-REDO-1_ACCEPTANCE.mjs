import fs from "node:fs";
const app=fs.readFileSync(new URL("./ETHICS-SUPER-REDO-1.html",import.meta.url),"utf8");
const routing=JSON.parse(fs.readFileSync(new URL("./ETHICS-PB-URL-BIND-1_MANIFEST.json",import.meta.url),"utf8"));
const redirect=fs.readFileSync(new URL("./ETHICS-SUPER-FINAL-1.html",import.meta.url),"utf8");
const checks=[];let pass=true;
const check=(name,ok)=>{checks.push({name,pass:!!ok});if(!ok)pass=false};
check("redo build identity",app.includes('ETHICS-SUPER-REDO-1'));
check("PROD-3 content lock",app.includes('"content_version":"ETHICS-PB-PROD-3"'));
check("routing is loaded from binding manifest",app.includes("fetch(ROUTING_PATH")&&app.includes("ETHICS-PB-URL-BIND-1_MANIFEST.json"));
check("12 routing chapters",routing.chapters.length===12);
check("12 verified Pressbooks returns",routing.chapters.every(c=>!!c.pressbooks.verified_chapter_url&&c.return_to_chapter.verified_url===c.pressbooks.verified_chapter_url));
check("45 targeted readings",routing.chapters.reduce((n,c)=>n+c.targeted_readings.length,0)===45);
check("targets use verified chapter + label",routing.chapters.every(c=>c.targeted_readings.every(r=>r.verified_url===c.pressbooks.verified_chapter_url&&!!r.heading)));
check("all workbook routes point to redo",routing.chapters.every(c=>c.workbook.url.includes("ETHICS-SUPER-REDO-1.html#chapter="+c.id+"&view=workbook")));
check("legacy FINAL-1 compatibility redirect",redirect.includes("ETHICS-SUPER-REDO-1.html'+location.hash"));
check("local persistence migration",app.includes("LEGACY_APP_KEY")&&app.includes("migrated_from"));
check("PFLAB-2 binding",app.includes("ETHICS-PFLAB-2.html")&&!app.includes("ETHICS-PFLAB-INTEGRATION-1.html"));
check("PFLAB source build",app.includes("source_build:BUILD_ID"));
check("PFLAB PROD-3 handoff",app.includes("content_version:'ETHICS-PB-PROD-3'"));
check("four-move grammar retained",(app.match(/"moves":\[/g)||[]).length===12);
check("Output Card IDs retained",(app.match(/"output_card_id":"OC-CH/g)||[]).length===12);
check("REOPEN retained",app.includes("REOPEN this chapter")&&app.includes("reopen_ledger"));
check("no Canvas hard-coupling",!routing.chapters.some(c=>JSON.stringify(c).match(/instructure\.com|canvas\./i)));
check("reduced motion",app.includes("prefers-reduced-motion:reduce"));
check("mobile breakpoint",app.includes("@media(max-width:560px)"));
check("aria live feedback",app.includes('aria-live="polite"'));
console.log(JSON.stringify({build:"ETHICS-SUPER-REDO-1",pass,checks,chapter_ledger:routing.chapters.map(c=>({chapter:c.id,targeted_readings:c.targeted_readings.length,pressbooks_return:!!c.return_to_chapter.verified_url,workbook_route:c.workbook.url}))},null,2));
if(!pass)process.exit(1);
